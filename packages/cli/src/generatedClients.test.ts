import fs from "node:fs";
import os from "node:os";
import path from "node:path";

import { afterEach, beforeEach, describe, expect, it } from "vitest";

import {
  clientGeneratedFrom,
  generatedClientsUnder,
} from "./generatedClients.js";

const TITLE = "Ledger Service";
// A generator copies the document's description into every file's
// comment, and one of a few kilobytes pushes its own line past the top.
const DESCRIPTION = "The ledger keeps every entry it accepts. ".repeat(60);
const DOCS = Array.from({ length: 24 }, (_, at) => `docs/Model${at}.md`);

let root: string;

beforeEach(() => {
  root = fs.mkdtempSync(path.join(os.tmpdir(), "suss-generated-clients-"));
});

afterEach(() => {
  fs.rmSync(root, { recursive: true, force: true });
});

/** A generator's output folder, with `FILES` listing what it wrote unless `listed` is null. */
function writeClient(
  folder: string,
  files: Record<string, string>,
  listed: readonly string[] | null,
): void {
  const at = path.join(root, folder);
  fs.mkdirSync(path.join(at, ".openapi-generator"), { recursive: true });
  for (const [file, text] of Object.entries(files)) {
    fs.mkdirSync(path.dirname(path.join(at, file)), { recursive: true });
    fs.writeFileSync(path.join(at, file), text);
  }
  if (listed !== null) {
    fs.writeFileSync(
      path.join(at, ".openapi-generator", "FILES"),
      `${listed.join("\n")}\n`,
    );
  }
}

function matched(): string | undefined {
  return clientGeneratedFrom(generatedClientsUnder(root), TITLE)?.directory;
}

const README = `# ledger_client\n\nThe client for the ${TITLE}\n\n${DESCRIPTION}\n\nThis SDK is automatically generated by the OpenAPI Generator project.\n`;

describe("a client generated with a long description", () => {
  it("matches a Ruby gem under vendor whose code comes after its docs in FILES", () => {
    const header = `=begin\n#${TITLE}\n\n#${DESCRIPTION}\n\nThe version of the OpenAPI document: 1.0.0\n\nGenerated by: https://openapi-generator.tech\nGenerator version: 7.10.0\n\n=end\n`;
    writeClient(
      "vendor/ledger_client",
      {
        ".rspec": "--color\n",
        "README.md": README,
        "lib/ledger_client.rb": `${header}\nmodule LedgerClient\nend\n`,
      },
      [
        ".gitignore",
        ".rspec",
        ".travis.yml",
        "Gemfile",
        "README.md",
        "Rakefile",
        ...DOCS,
        "git_push.sh",
        "ledger_client.gemspec",
        "lib/ledger_client.rb",
      ],
    );

    expect(matched()).toBe(path.join("vendor", "ledger_client"));
  });

  it("matches a Python package whose header starts with an encoding line", () => {
    const header = `# coding: utf-8\n\n# flake8: noqa\n\n"""\n    ${TITLE}\n\n    ${DESCRIPTION}\n\n    The version of the OpenAPI document: 1.0.0\n    Generated by OpenAPI Generator (https://openapi-generator.tech)\n\n    Do not edit the class manually.\n"""  # noqa: E501\n`;
    writeClient(
      "clients/ledger",
      {
        "README.md": README,
        "ledger_client/__init__.py": `${header}\n__version__ = "1.0.0"\n`,
      },
      [
        ".github/workflows/python.yml",
        ".gitignore",
        "README.md",
        ...DOCS,
        "git_push.sh",
        "ledger_client/__init__.py",
        "pyproject.toml",
      ],
    );

    expect(matched()).toBe(path.join("clients", "ledger"));
  });

  it("matches a TypeScript client whose index has no comment of its own", () => {
    const header = `/* tslint:disable */\n/* eslint-disable */\n/**\n * ${TITLE}\n * ${DESCRIPTION}\n *\n * The version of the OpenAPI document: 1.0.0\n *\n * NOTE: This class is auto generated by OpenAPI Generator (https://openapi-generator.tech).\n */\n`;
    writeClient(
      "src/generated/ledger",
      {
        "index.ts": `/* tslint:disable */\n/* eslint-disable */\nexport * from "./runtime";\n`,
        "runtime.ts": `${header}\nexport class BaseAPI {}\n`,
      },
      ["README.md", ...DOCS, "index.ts", "runtime.ts"],
    );

    expect(matched()).toBe(path.join("src", "generated", "ledger"));
  });

  it("finds the code by walking a client that has no FILES list", () => {
    writeClient(
      "vendor/ledger_client",
      {
        "README.md": README,
        "lib/ledger_client.rb": `=begin\n#${TITLE}\n\n#${DESCRIPTION}\n=end\n`,
      },
      null,
    );

    expect(matched()).toBe(path.join("vendor", "ledger_client"));
  });

  it("leaves a README that mentions the title in a sentence unmatched", () => {
    writeClient("vendor/ledger_client", { "README.md": README }, ["README.md"]);

    expect(matched()).toBeUndefined();
  });
});
